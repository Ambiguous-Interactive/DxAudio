#!/usr/bin/env python3
"""Enforce the assembly warning policy (issues #37 and #40).

A compiler warning the package hides is a defect no CI lane can see, so the
package compiles every assembly with every warning promoted to an error and
fails the ladder when that policy is missing or weakened:

1. Every directory holding an assembly definition carries the generated policy:
   a ``csc.rsp`` whose only switch is the maximum warning level and a
   ``WarningsAsErrors.ruleset`` that promotes every diagnostic. The files are
   generated by ``scripts/sync_compiler_policy.py`` and gitignored, so no
   consumer compiles with them and a hand edit cannot hide a warning.
2. No other response file or ruleset ships in the repository. Unity feeds a
   response file beside an assembly definition into that assembly's compile, so
   one anywhere else can silence a warning without a reviewable C# change.
3. No ``#pragma warning disable`` in the shipped ``Runtime/`` and ``Editor/``
   sources. Fix the warning or version-guard the API that raises it, per the
   unity-version-guards skill. C# requires a directive to start its line, so
   the scan anchors there and prose that mentions the form stays clean.
4. The engine-free ``.net-tests`` project keeps ``TreatWarningsAsErrors`` set
   to true as its last word, so the Core assembly fails on a warning on plain
   .NET before Unity sees it.

The ``Tests/`` tree stays out of rule 3: a Unity test fixture may pin one
editor's obsolete API and suppress the warning the other editor raises.

The step runs in the fast check (on a changed assembly definition, response
file, ruleset, or shipped source), in the gate, and in CI's lint ladder, so all
three drivers apply one policy.

Launch with ``uv run scripts/lint_assembly_warnings.py``; any Python 3.9+
interpreter works. ``--verbose`` prints the scanned counts when the policy
holds. Exit codes: 0 = policy holds, 1 = a violation or an unreadable input.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path
from typing import List, Optional, Sequence, Tuple

sys.dont_write_bytecode = True

from sync_compiler_policy import (
    GENERATED_POLICY,
    POLICY_RESPONSE_FILE,
    POLICY_RULESET_FILE,
    SKIPPED_DIRECTORY_NAMES,
    assembly_directories,
    display_path,
)

REPO_ROOT = Path(__file__).resolve().parent.parent
SHIPPED_SOURCE_ROOTS: Tuple[str, ...] = ("Runtime", "Editor")
GENERATED_NAMES = frozenset(name for name, _ in GENERATED_POLICY)
FORBIDDEN_CONFIGURATION_SUFFIXES: Tuple[str, ...] = (".rsp", ".ruleset")
ENGINE_FREE_PROJECT = Path(".net-tests") / "DxAudio.Tests.csproj"
WARNING_DISABLE_PATTERN = re.compile(r"^\s*#\s*pragma\s+warning\s+disable\b", re.IGNORECASE)
WARNINGS_AS_ERRORS_PATTERN = re.compile(r"<TreatWarningsAsErrors>\s*(\w+)\s*</TreatWarningsAsErrors>", re.IGNORECASE)


def parse_arguments(argv: Optional[Sequence[str]] = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="lint-assembly-warnings",
        description="Fail when the package hides a compiler warning.",
    )
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=REPO_ROOT,
        help="repository root to scan (default: the checkout holding this script)",
    )
    parser.add_argument("--verbose", action="store_true", help="print the scanned counts when the policy holds")
    return parser.parse_args(argv)


def _walk(repo_root: Path) -> Tuple[List[Path], List[Path]]:
    """Return (compiler configuration files, shipped C# sources) in one walk."""
    configuration: List[Path] = []
    sources: List[Path] = []
    for directory, subdirectories, names in os.walk(repo_root):
        subdirectories[:] = sorted(
            name for name in subdirectories if name not in SKIPPED_DIRECTORY_NAMES and not name.endswith("~")
        )
        current = Path(directory)
        relative = display_path(current, repo_root)
        shipped = bool(relative) and relative.split("/")[0] in SHIPPED_SOURCE_ROOTS
        for name in names:
            path = current / name
            lowered = name.lower()
            if lowered.endswith(FORBIDDEN_CONFIGURATION_SUFFIXES):
                configuration.append(path)
            elif shipped and lowered.endswith(".cs"):
                sources.append(path)
    return sorted(configuration, key=str), sorted(sources, key=str)


def _policy_violations(repo_root: Path, directories: Sequence[Path]) -> List[str]:
    """Name every assembly directory whose generated policy is missing or weakened."""
    violations: List[str] = []
    for directory in directories:
        for name, content in GENERATED_POLICY:
            path = directory / name
            try:
                present = path.read_text(encoding="utf-8")
            except OSError:
                violations.append(
                    f"{display_path(path, repo_root)} is missing; run scripts/sync_compiler_policy.py, "
                    "because every assembly must compile with warnings as errors"
                )
                continue
            if present != content:
                violations.append(
                    f"{display_path(path, repo_root)} does not carry the generated policy; "
                    f"run scripts/sync_compiler_policy.py, because only {POLICY_RESPONSE_FILE} with the maximum "
                    f"warning level and {POLICY_RULESET_FILE} promoting every warning are accepted"
                )
    return violations


def find_policy_violations(repo_root: Path) -> Tuple[List[str], int, int]:
    """Return the policy violations, the configuration count and the source count."""
    configuration, sources = _walk(repo_root)
    directories = assembly_directories(repo_root)
    violations: List[str] = _policy_violations(repo_root, directories)
    generated = {directory / name for directory in directories for name, _ in GENERATED_POLICY}

    for path in configuration:
        if path not in generated:
            violations.append(
                f"{display_path(path, repo_root)} configures the package compiler; "
                "remove it, because a response file or ruleset can hide a warning"
            )

    for path in sources:
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError as error:
            violations.append(f"{display_path(path, repo_root)} cannot be read: {error}")
            continue
        for number, line in enumerate(text.splitlines(), start=1):
            if WARNING_DISABLE_PATTERN.search(line):
                violations.append(
                    f"{display_path(path, repo_root)}:{number} disables a compiler warning; "
                    "fix the warning or version-guard the API"
                )

    project = repo_root / ENGINE_FREE_PROJECT
    try:
        project_text = project.read_text(encoding="utf-8")
    except OSError:
        violations.append(f"{ENGINE_FREE_PROJECT.as_posix()} is missing; the engine-free build must fail on a warning")
    else:
        # MSBuild is last-wins, so a later false must fail the policy even
        # though an earlier true is present.
        settings = [value.lower() for value in WARNINGS_AS_ERRORS_PATTERN.findall(project_text)]
        if not settings or settings[-1] != "true":
            violations.append(
                f"{ENGINE_FREE_PROJECT.as_posix()} must set "
                "<TreatWarningsAsErrors>true</TreatWarningsAsErrors>"
            )

    return violations, len(configuration), len(sources)


def main(argv: Optional[Sequence[str]] = None) -> int:
    options = parse_arguments(argv)
    repo_root = Path(os.path.abspath(options.repo_root))
    if not repo_root.is_dir():
        print(f"[assembly-warnings] error: repository root does not exist: {repo_root}")
        return 1

    violations, configuration, sources = find_policy_violations(repo_root)
    if violations:
        for violation in violations:
            print(f"[assembly-warnings] error: {violation}")
        print(f"[assembly-warnings] failed: {len(violations)} assembly warning policy violation(s)")
        return 1

    if options.verbose:
        print(
            f"[assembly-warnings] ok: {len(assembly_directories(repo_root))} assembly director(ies) carry the "
            f"generated policy, {configuration} compiler configuration file(s), {sources} shipped source file(s), "
            "and the engine-free warnings-as-errors setting hold"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
